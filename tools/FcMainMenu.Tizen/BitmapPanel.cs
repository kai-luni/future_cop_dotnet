    public static void Render(byte[] rgb, MenuPanel panel)
    {
        if (rgb == null) throw new ArgumentNullException(nameof(rgb));
        if (panel == null) throw new ArgumentNullException(nameof(panel));
        if (rgb.Length < Width * Height * 3) throw new ArgumentException("Buffer too small", nameof(rgb));

        for (int i = 0; i < Width * Height * 3; i += 3)
        {
            rgb[i] = 0x10;
            rgb[i + 1] = 0x18;
            rgb[i + 2] = 0x2e;
        }

        DrawCentered(rgb, panel.Heading, 50, 0x73, 0xc5, 0xff);
        for (int i = 0; i < panel.Entries.Count; i++)
        {
            bool selected = i == panel.Selected;
            DrawCentered(rgb, panel.Entries[i], 84 + i * 16, 0xff, 0xff, selected ? (byte)0x80 : (byte)0xff);
        }
        DrawCentered(rgb, panel.Hint, 218, 0xc0, 0xc0, 0xc0);
    }

    private static void DrawCentered(byte[] rgb, string text, int menuY, byte r, byte g, byte b)
    {
        if (string.IsNullOrEmpty(text)) return;
        int scale = text.Length * GlyphAdvance * 2 <= Width - 16 ? 2 : 1;
        int textWidth = (text.Length * GlyphAdvance - 1) * scale;
        int startX = Math.Max(0, (Width - textWidth) / 2);
        int centerY = menuY * 2 + 9;
        int startY = Math.Max(0, centerY - (GlyphHeight * scale) / 2);

        int penX = startX;
        foreach (char raw in text)
        {
            int idx = raw >= 0x20 && raw <= 0x7E ? raw - 0x20 : '?' - 0x20;
            int offset = idx * GlyphHeight;
            for (int row = 0; row < GlyphHeight; row++)
            {
                byte bits = Font5x7[offset + row];
                for (int col = 0; col < GlyphWidth; col++)
                {
                    if ((bits & (1 << (4 - col))) == 0) continue;
                    for (int dy = 0; dy < scale; dy++)
                    {
                        int py = startY + row * scale + dy;
                        if ((uint)py >= Height) continue;
                        for (int dx = 0; dx < scale; dx++)
                        {
                            int px = penX + col * scale + dx;
                            if ((uint)px >= Width) continue;
                            int p = (py * Width + px) * 3;
                            rgb[p] = r;
                            rgb[p + 1] = g;
                            rgb[p + 2] = b;
                        }
                    }
                }
            }
            penX += GlyphAdvance * scale;
        }
    }
