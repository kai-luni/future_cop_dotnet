#!/bin/bash
# Regenerate tests/golden/mech-walk.vectors from the case inputs in mech-walk.cases by running the
# UNCHANGED decomp units (mech_test.sh --emit). Expectations therefore come from the original C,
# never from the .NET port. Writes to stdout; review the diff before replacing the golden file:
#   bash tests/host/mech/regen_vectors.sh > tests/golden/mech-walk.vectors
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
CASES="${MECH_CASES:-$HERE/mech-walk.cases}"
emitted="$(MECH_VECTORS="$CASES" bash "$HERE/mech_test.sh" --emit)"
cat <<'EOF'
# fcop-mech-walk-golden/v1
# Shared vectors for the walker locomotion of the player mech (C harness + .NET port).
# Generated by tests/host/mech/regen_vectors.sh from tests/host/mech/mech-walk.cases: every
# expectation behind '->' was printed by the UNCHANGED decomp units under qemu-mipsel
# (tests/host/mech/mech_test.sh --emit), not by the .NET code. GTE instructions ran against the
# software GTE model of the harness (cop2 trap), so this is C-semantics parity, not a PS1
# hardware measurement. Terrain: Ctil/Cptc of the MIS line (relative to build/disc/files).
#
# Positional kinds (inputs -> outputs, hex outputs):
#   SQRT v                    func_80095900 gSqrt12 (GTE LZCS/LZCR + ROM table D_8009DF20)
#   NORM x y z                func_8001A180 gNormalizeVector -> x y z
#   NLEN x y z                func_8001A314 gNormalizeGetLength -> len x y z
#   LEN2 x z                  func_8001A7AC (2D length, normalises in place) -> len x z
#   SINCOS a                  func_8001846C gSinCos (ROM table D_8009A234) -> sin cos
#   STICK type x y lock freeze port flags
#                             func_800538C8 with the real func_8001E7B8 (pad type, left stick
#                             bytes) -> status flags magV magH (0x5a5a = not written)
#   PAD b0 b1 players         func_8001E588 default map + func_8001E620/func_8001EF8C via
#                             func_80057864, then func_800576A8 per port
#                             -> word0 word1 translated0 translated1 (b = PS1 buttons, 1 = held:
#                             bit0 select 3 start 4 up 5 right 6 down 7 left 8 L2 9 R2 10 L1
#                             11 R1 12 triangle 13 circle 14 cross 15 square)
#   RAY px py pz qx qy qz flag s1
#                             func_800684AC/func_80067914 grid ray; s1 = the caller's $s1 that
#                             func_80067914 reads as stale bestDist -> result outA0..2 outB
#   GROUND x y z              func_80066F78(pos, normal, &attr, &surface), empty object queue
#                             -> height nx ny nz attr surface
# Named kinds (name=value; every field of the harness table is printed after '->'):
#   DELTA  func_80054590(self, a0 speed, a1 lane, out, a2 direction) -> o0..o2
#   IMPULSE func_80052550(self, vec a0..a2) -> ret, o0..o2
#   SURF   func_80053188(self, a0 attribute)
#   FOOT   func_80052708(self, a0)
#   ANIM   func_80044B34(self, &track, a0 speed, a1 direction) -> ret
#   WALK   func_800549F0(self, 0, steps, flags) -> ret (impact damage)
# Stateful jump sequences (retail C entity, world and PRNG survive between calls):
#   JUMP_INIT <named fields>  initialize once using the current CLIPS table -> all fields
#   JUMP_STEP buttons steps  raw PS1 buttons, then default pad mapping and a WALK tick
#                            -> flags x y z motionY state bits timer trackClip trackFrame
#                               trackElapsed impactDamage eventCount firstEvent boundsHigh boundsLow
#   JUMP_RANDOM 3            end the sequence -> three draws from the surviving primary PRNG
# Record fields: evn/ev0..3 = func_80047088 events (sound, not executed), msgn/msgcode/msgid/
# msgval/msgkind = func_8005908C messages, framen/frame = func_800175F8 calls, hudr/hudl =
# record written by func_80051AC8. CLIPS = AnmD clip table (10 values per 16-byte record).
EOF
printf '%s\n' "$emitted"
